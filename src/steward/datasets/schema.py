"""Pydantic schemas for synthetic STE-oriented dataset records.

Every record is a *candidate*. Nothing in these records states or implies
ASD-STE100 compliance; see :data:`COMPLIANCE_NOTE`.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Literal

from pydantic import AwareDatetime, BaseModel, ConfigDict, Field, JsonValue, model_validator

SCHEMA_VERSION: Literal["1.1"] = "1.1"
"""Version of the record schema. 1.1 adds task types, source language, and entities.

Records with version 1.0 still load: the new fields have defaults.
"""

SourceLanguage = Literal["en", "de", "fr", "ro"]
"""Languages accepted as source input. Targets are always English."""

COMPLIANCE_NOTE = (
    "STE-oriented candidate generated by a language model. "
    "Not verified or certified as ASD-STE100 compliant."
)
"""Fixed note stored on every record."""

FICTION_NOTE = (
    "Fictional synthetic text. Values, parts, and steps are invented and are not "
    "approved aircraft maintenance instructions."
)


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class TaskType(StrEnum):
    """The kind of learning task an example represents."""

    PLAIN_TO_STE_REWRITE = "plain_to_ste_rewrite"
    """Ordinary English to STE-oriented English."""
    MULTILINGUAL_TO_STE = "multilingual_to_ste_translation"
    """German, French, or Romanian input to STE-oriented English."""
    REQUIREMENTS_TO_STE = "requirements_to_ste"
    """Structured technical information (any supported language) to STE text."""
    STE_IDENTITY = "ste_identity"
    """Text that already passes the checks; the target is the unchanged input."""
    OUT_OF_DOMAIN = "out_of_domain"
    """Not technical documentation; the target is the controlled-failure sentinel."""


class TaskCategory(StrEnum):
    """The kind of technical text in an example."""

    PROCEDURE = "procedure"
    DESCRIPTION = "description"
    SAFETY_NOTICE = "safety_notice"
    TROUBLESHOOTING = "troubleshooting"


class ReviewState(StrEnum):
    """Review state labels allowed by the project policy (AGENTS.md)."""

    CANDIDATE = "candidate"
    LINTED = "linted"
    REVIEWED = "reviewed"
    VALIDATED_AGAINST_AVAILABLE_CHECKS = "validated_against_available_checks"


class Severity(StrEnum):
    """Severity of a failed check. Only ``error`` causes rejection."""

    ERROR = "error"
    WARNING = "warning"
    INFO = "info"


class CheckKind(StrEnum):
    """Whether a check is exact (deterministic) or approximate (heuristic)."""

    DETERMINISTIC = "deterministic"
    HEURISTIC = "heuristic"


class CheckResult(_Strict):
    """The result of one validation check."""

    check_id: str
    passed: bool
    severity: Severity
    kind: CheckKind
    message: str
    details: dict[str, JsonValue] = Field(default_factory=dict)


class ValidationReport(_Strict):
    """Results of the pre-lint sanity checks run at generation time.

    These checks are not an STE linter and not a compliance assessment.
    Build instances with :meth:`from_checks` so ``passed`` is derived.
    """

    checker_version: str
    checks: list[CheckResult]
    passed: bool
    failed_check_ids: list[str]
    note: str = "Pre-lint sanity checks only. Not an ASD-STE100 compliance assessment."

    @classmethod
    def from_checks(cls, checker_version: str, checks: list[CheckResult]) -> ValidationReport:
        """Create a report; ``passed`` is true when no ``error`` check failed."""
        return cls(
            checker_version=checker_version,
            checks=checks,
            passed=_passed(checks),
            failed_check_ids=[c.check_id for c in checks if not c.passed],
        )

    @model_validator(mode="after")
    def _consistent(self) -> ValidationReport:
        if self.passed != _passed(self.checks):
            raise ValueError("'passed' does not match the check results")
        if self.failed_check_ids != [c.check_id for c in self.checks if not c.passed]:
            raise ValueError("'failed_check_ids' does not match the check results")
        return self


def _passed(checks: list[CheckResult]) -> bool:
    return not any(c.severity is Severity.ERROR and not c.passed for c in checks)


class SamplingParameters(_Strict):
    """Decoding parameters sent to the teacher model."""

    temperature: float = Field(ge=0.0, le=2.0)
    top_p: float = Field(default=1.0, gt=0.0, le=1.0)
    top_k: int | None = Field(default=None, ge=1)
    seed: int | None = None
    max_tokens: int = Field(default=1024, ge=1)


class PromptRef(_Strict):
    """A pointer to the exact prompt template that was used."""

    template_id: str
    version: int = Field(ge=1)
    sha256: str = Field(pattern=r"^[0-9a-f]{64}$")

    @property
    def ref(self) -> str:
        """Return the ``id@version`` reference string."""
        return f"{self.template_id}@{self.version}"


class PromptVersions(_Strict):
    """Prompt templates used for each generation stage."""

    source: PromptRef
    rewrite: PromptRef
    repair: PromptRef | None = None
    """Set when the candidate was revised by ``steward dataset repair``."""


class GenerationParameters(_Strict):
    """The sampling parameters that were actually used for each stage."""

    source: SamplingParameters
    rewrite: SamplingParameters
    repair: SamplingParameters | None = None


class StageStats(_Strict):
    """Timing and token statistics for one generation stage."""

    stage: Literal["source", "rewrite", "repair"]
    attempts: int = Field(ge=1)
    latency_s: float = Field(ge=0.0)
    prompt_tokens: int | None = None
    completion_tokens: int | None = None


class TeacherModel(_Strict):
    """Identity of the teacher model that produced the text."""

    provider: str
    model: str
    digest: str | None = None
    provider_version: str | None = None
    details: dict[str, JsonValue] = Field(default_factory=dict)


class Scenario(_Strict):
    """The sampled scenario that seeded one example."""

    index: int = Field(ge=0)
    category: TaskCategory
    topic: str
    audience: str
    sentence_count: int = Field(ge=1)
    task_type: TaskType = TaskType.PLAIN_TO_STE_REWRITE
    source_language: SourceLanguage = "en"
    focus: str | None = Field(default=None, exclude_if=lambda v: v is None)
    """Targeted failure mode (for example ``terminology``), when the config has a focus mix."""
    focus_detail: str | None = Field(default=None, exclude_if=lambda v: v is None)
    """The sampled focus option, for example ``Mutter|threaded nut|nut``."""
    required_terms: list[str] | None = Field(default=None, exclude_if=lambda v: v is None)
    """English words the target must contain for this focus (checked by ``prelint-3``)."""


class Provenance(_Strict):
    """Where, when, and how a record was produced."""

    run_id: str
    created_at: AwareDatetime
    steward_version: str
    git_commit: str | None = None
    git_dirty: bool | None = None
    config_sha256: str
    environment: dict[str, str]
    scenario: Scenario
    synthetic: Literal[True] = True
    fictional: Literal[True] = True
    fiction_note: str = FICTION_NOTE
    data_license: str = "pending-rights-review"
    teacher_terms_reviewed: bool = False


CritiqueCategory = Literal[
    "mistranslated_term",
    "untranslated_word",
    "negation_changed",
    "condition_changed",
    "label_changed",
    "value_changed",
    "step_missing",
    "step_added",
    "order_changed",
    "contradiction",
]


class CritiqueProblem(_Strict):
    """One problem that the critic model reported."""

    category: CritiqueCategory
    severity: Literal["critical", "minor"]
    source_span: str = ""
    target_span: str = ""
    explanation: str = ""


class LlmReview(_Strict):
    """An independent LLM critique of one example.

    ``method`` is always ``llm_judged``: this is not a deterministic check and not a
    human review. The final verdict refers to the final candidate.
    """

    method: Literal["llm_judged"] = "llm_judged"
    critic_provider: str
    critic_model: str
    critic_digest: str | None = None
    prompt: PromptRef
    verdict: Literal["pass", "fail"]
    problems: list[CritiqueProblem] = Field(default_factory=list)
    rounds: int = Field(default=0, ge=0, description="Critique-guided revisions applied.")
    status: Literal["passed", "revised", "failed", "error"]
    reviser_model: str | None = None
    revise_prompt: PromptRef | None = None
    initial_problems: list[CritiqueProblem] = Field(default_factory=list)
    """Problems of the first critique, before any revision."""
    reviewed_at: AwareDatetime

    @property
    def critical(self) -> list[CritiqueProblem]:
        """Critical problems of the final candidate."""
        return [p for p in self.problems if p.severity == "critical"]


class DatasetExample(_Strict):
    """One accepted synthetic plain-English to STE-oriented rewrite example."""

    schema_version: Literal["1.0", "1.1"] = SCHEMA_VERSION
    example_id: str = Field(pattern=r"^stew-[0-9a-f]{16}$")
    task_type: TaskType = TaskType.PLAIN_TO_STE_REWRITE
    task_category: TaskCategory
    source_language: SourceLanguage = "en"
    source_title: str
    source_text: str = Field(min_length=1)
    ste_candidate: str = Field(min_length=1)
    technical_entities: list[str] = Field(
        default_factory=list,
        description="Identifiers and measurements that occur in the source and must be kept.",
    )
    safety_constraints: list[str] = Field(
        default_factory=list,
        description="Safety-critical constraints in the source (warnings, cautions, limits).",
    )
    teacher: TeacherModel
    prompt_version: PromptVersions
    generation_parameters: GenerationParameters
    stages: list[StageStats]
    validation: ValidationReport
    review_state: ReviewState = ReviewState.CANDIDATE
    compliance_note: str = COMPLIANCE_NOTE
    provenance: Provenance
    pre_repair_candidate: str | None = None
    """The teacher's candidate before linter-guided repair, kept for analysis."""
    llm_review: LlmReview | None = Field(default=None, exclude_if=lambda v: v is None)
    """Independent LLM fidelity critique (an LLM judgement, never proof of correctness)."""
    pre_revision_candidate: str | None = Field(default=None, exclude_if=lambda v: v is None)
    """The candidate before the critique-guided revision, kept for analysis."""


class RejectionReason(StrEnum):
    """Why an attempted example was not accepted."""

    PROVIDER_ERROR = "provider_error"
    MALFORMED_OUTPUT = "malformed_output"
    FAILED_VALIDATION = "failed_validation"
    DUPLICATE = "duplicate"


class RejectedExample(_Strict):
    """An attempted example that was not accepted. Kept for analysis only."""

    schema_version: Literal["1.0", "1.1"] = SCHEMA_VERSION
    rejection_id: str
    reason: RejectionReason
    message: str
    created_at: datetime
    run_id: str
    scenario: Scenario
    teacher_model: str
    source_text: str | None = None
    ste_candidate: str | None = None
    duplicate_of: str | None = None
    validation: ValidationReport | None = None
