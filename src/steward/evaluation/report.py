"""Generate the benchmark report, summary JSON, and README section.

Everything here is derived from committed files only (history, suite,
registry, thresholds), so the output is identical on every machine.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from steward.evaluation.compare import (
    Comparison,
    compare,
    latest_by_candidate,
    references_for,
    select_model,
)
from steward.evaluation.metrics import METRICS
from steward.evaluation.plots import FIGURES
from steward.evaluation.project import BenchmarkProject
from steward.evaluation.records import BenchmarkRecord, RecordStatus
from steward.evaluation.status import evaluator_version_warnings, pending_candidates
from steward.evaluation.suite import Bound, SelectionRequirements

README_START = "<!-- benchmarks:start -->"
README_END = "<!-- benchmarks:end -->"
HEADER = "<!-- Generated by `steward benchmark report`. Do not edit by hand. -->"

TABLE_METRICS = [
    ("ste_rule_pass_rate", "STE pass", "{:.2f}"),
    ("violations_per_100_words", "Viol./100w", "{:.1f}"),
    ("grammar_violations_per_100_words", "Gram./100w", "{:.1f}"),
    ("meaning_preservation", "Meaning", "{:.2f}"),
    ("hallucination_rate", "Halluc.", "{:.2f}"),
    ("missing_information_rate", "Missing", "{:.2f}"),
    ("critical_failures", "Critical", "{:.0f}"),
    ("task_completion_rate", "Complete", "{:.2f}"),
    ("tokens_per_s", "Tok/s", "{:.0f}"),
    ("latency_mean_s", "Latency s", "{:.2f}"),
]


def _fmt(record: BenchmarkRecord, name: str, fmt: str) -> str:
    metric = record.metrics.get(name)
    if metric is None or metric.value is None:
        return "n/a"
    text = fmt.format(metric.value)
    if metric.ci_low is not None and metric.ci_high is not None and name == "ste_rule_pass_rate":
        text += f" [{metric.ci_low:.2f}, {metric.ci_high:.2f}]"
    return text


def _params(record: BenchmarkRecord) -> str:
    count = record.candidate.parameter_count
    return f"{count / 1e9:.2f}B" if count else "n/a"


STE_ONLY_TABLE = [
    # Primary: safety and technical fidelity first.
    ("critical_technical_errors", "Tech. errors", "{:.0f}"),
    ("critical_failures", "Critical", "{:.0f}"),
    ("meaning_preservation", "Meaning", "{:.2f}"),
    ("negation_preservation", "Negation", "{:.2f}"),
    ("safety_label_preservation", "Labels", "{:.2f}"),
    ("terminology_preservation", "IDs", "{:.2f}"),
    ("unsupported_addition_rate", "Added", "{:.2f}"),
    ("ste_only_output_rate", "STE-only", "{:.2f}"),
    ("ste_rule_pass_rate", "STE pass", "{:.2f}"),
    # Secondary.
    ("controlled_failure_reliability", "OOD refusal", "{:.2f}"),
    ("unnecessary_rewrite_rate", "Rewrote STE", "{:.2f}"),
    ("non_english_output_rate", "Non-EN", "{:.2f}"),
    ("chrf_mean", "chrF", "{:.1f}"),
    ("latency_mean_s", "Latency s", "{:.2f}"),
]


def _requirements(project: BenchmarkProject, name: str) -> SelectionRequirements | dict[str, Bound]:
    suite = project.suite_named(name)
    return project.thresholds.selection_by_suite.get(
        suite.manifest.id, project.thresholds.selection
    )


def comparisons(project: BenchmarkProject, name: str | None = None) -> list[Comparison]:
    """Compare each latest comparable result with its required references."""
    key = project.key_for(name) if name else project.key
    latest = latest_by_candidate(project.benchmarks(), key)
    result = []
    for record in sorted(latest.values(), key=lambda r: r.candidate.candidate_id):
        for kind, ref in references_for(record, latest):
            result.append(compare(record, ref, project.thresholds, kind))
    return result


def _suite_summary(project: BenchmarkProject, name: str) -> dict[str, Any]:
    key = project.key_for(name)
    latest = latest_by_candidate(project.benchmarks(), key)
    selected, failures = select_model(latest, _requirements(project, name))
    return {
        "comparability_key": key,
        "suite": project.suite_named(name).ref.model_dump(mode="json"),
        "candidates": {
            cid: {
                "experiment_id": r.experiment_id,
                "created_at": r.created_at.isoformat(),
                "role": r.candidate.role.value,
                "parameter_count": r.candidate.parameter_count,
                "metrics": {k: m.value for k, m in sorted(r.metrics.items())},
                "meets_requirements": not failures[cid],
                "requirement_failures": failures[cid],
            }
            for cid, r in sorted(latest.items())
        },
        "selected_model": selected.candidate.candidate_id if selected else None,
        "regressions": [
            {
                "candidate": c.candidate.candidate.candidate_id,
                "reference": c.reference.candidate.candidate_id,
                "reference_kind": c.reference_kind,
                "metric": f.metric,
                "kind": f.kind.value,
                "message": f.message,
            }
            for c in comparisons(project, name)
            for f in c.regressions
        ],
    }


def build_summary(project: BenchmarkProject) -> dict[str, Any]:
    """Machine-readable summary. Top-level fields describe the primary suite."""
    records = project.benchmarks()
    primary = _suite_summary(project, project.primary_suite_name)
    return {
        **primary,
        "primary_suite": project.primary_suite_name,
        "suites": {
            name: _suite_summary(project, name)
            for name in project.suite_names()
            if name != project.primary_suite_name
        },
        "training_runs": [
            {
                "run_id": t.summary.run_id,
                "status": t.status.value,
                "experiment_id": t.experiment_id,
                "dataset_fingerprint": t.summary.dataset_fingerprint,
                "label": t.summary.hyperparameters.get("label"),
            }
            for t in project.trainings()
        ],
        "pending_candidates": pending_candidates(project.registry, records, project.keys),
        "failed_experiments": [r.experiment_id for r in records if r.status is RecordStatus.FAILED],
        "history_records": len(project.history()),
    }


def _results_table(rows: list[BenchmarkRecord], table: list[tuple[str, str, str]]) -> list[str]:
    head = ["Candidate", "Role", "Params", "Quant."] + [h for _, h, _ in table] + ["Experiment"]
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        cells = [
            f"`{r.candidate.candidate_id}`",
            r.candidate.role.value,
            _params(r),
            r.candidate.quantization or "n/a",
            *(_fmt(r, name, fmt) for name, _, fmt in table),
            f"`{r.experiment_id}`",
        ]
        out.append("| " + " | ".join(cells) + " |")
    return out


def _group(record: BenchmarkRecord, group: str, metric: str, fmt: str) -> str:
    m = record.by_category.get(group, {}).get(metric)
    return "n/a" if m is None or m.value is None else fmt.format(m.value)


def _language_table(rows: list[BenchmarkRecord]) -> list[str]:
    langs = ["en", "de", "fr", "ro"]
    head = ["Candidate"] + [f"{lang} meaning / chrF / STE-only" for lang in langs]
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        cells = [f"`{r.candidate.candidate_id}`"]
        for lang in langs:
            g = f"lang:{lang}"
            cells.append(
                f"{_group(r, g, 'meaning_preservation', '{:.2f}')} / "
                f"{_group(r, g, 'chrf_mean', '{:.1f}')} / "
                f"{_group(r, g, 'ste_only_output_rate', '{:.2f}')}"
            )
        out.append("| " + " | ".join(cells) + " |")
    return out


def _requirements_text(req: SelectionRequirements | dict[str, Bound]) -> str:
    if isinstance(req, dict):
        parts = []
        for name, bound in req.items():
            if bound.min is not None:
                parts.append(f"{name} >= {bound.min}")
            if bound.max is not None:
                parts.append(f"{name} <= {bound.max}")
        return ", ".join(parts) + "."
    return (
        f"STE pass rate >= {req.min_ste_rule_pass_rate}, meaning preservation >= "
        f"{req.min_meaning_preservation}, hallucination rate <= {req.max_hallucination_rate}, "
        f"missing-information rate <= {req.max_missing_information_rate}, critical failures <= "
        f"{req.max_critical_failures}, task completion >= {req.min_task_completion_rate}."
    )


def _suite_section(project: BenchmarkProject, name: str, *, primary: bool) -> list[str]:
    suite = project.suite_named(name)
    key = project.key_for(name)
    latest = latest_by_candidate(project.benchmarks(), key)
    rows = sorted(
        latest.values(), key=lambda r: (r.candidate.parameter_count or 0, r.candidate.candidate_id)
    )
    text_contract = suite.manifest.contract == "ste_only_text"
    title = "Primary suite" if primary else "Other suite"
    out = [
        f"## {title}: `{suite.manifest.id}` v{suite.manifest.version}",
        "",
        f"* {len(suite.items)} items, sha256 `{suite.sha256[:16]}`, contract "
        f"`{suite.manifest.contract}`",
        f"* Review state: **{suite.manifest.review_state}**. {suite.manifest.author}",
        f"* Comparability key for new results: `{key}`",
        f"* Decoding: temperature {suite.manifest.sampling.temperature}, "
        f"seed {suite.manifest.sampling.seed}, max tokens {suite.manifest.sampling.max_tokens}",
        "",
    ]
    if suite.manifest.review_state == "draft":
        out += [
            "> **Draft suite.** A human has not reviewed the golden items yet. Treat these results",
            "> as development signals only, not as release evidence.",
            "",
        ]
    out += ["### Latest comparable results", ""]
    if not rows:
        out += ["No completed results for this suite and evaluator. Run `pixi run benchmark`.", ""]
    else:
        out += _results_table(rows, STE_ONLY_TABLE if text_contract else TABLE_METRICS)
        if text_contract:
            n_ood = sum(1 for i in suite.items if i.expected_unsupported)
            out += [
                "",
                f"Denominators: {len(suite.items) - n_ood} in-domain items for quality and "
                f"STE-only rates, {n_ood} out-of-domain items for the refusal rate, "
                f"{sum(1 for i in suite.items if i.task_type.value == 'ste_identity')} identity "
                "items for 'Rewrote STE'. Meaning is a fact proxy (numbers, measurements, "
                "identifiers, safety labels, required terms, negation). chrF is measured against "
                "draft reference texts. Guard pass = the inference output guard accepted or "
                "flagged (did not reject) the output. Tech. errors = in-domain items with a "
                "failed fidelity check (facts, labels, negation, order, terminology fixtures, "
                "untranslated words, contradiction, language, omission) or a refusal. Critical = "
                "safety-critical items with such an error, or a lost safety label. Safety and "
                "fidelity columns come first: a higher STE pass rate never outweighs more "
                "technical errors.",
                "",
                "### Results by source language",
                "",
                *_language_table(rows),
                "",
            ]
        else:
            out += [
                "",
                f"Denominators: {len(suite.items)} items per candidate; per-100-word rates use "
                "the output words of valid outputs. STE pass rate shows a 95% Wilson interval.",
                "",
            ]
    req = _requirements(project, name)
    selected, failures = select_model(latest, req)
    out += [
        "### Model selection",
        "",
        "The selected model is the **smallest** candidate that meets every requirement in "
        "`benchmarks/thresholds.toml`. Size decides only among candidates that meet all "
        "requirements:",
        "",
        _requirements_text(req),
        "",
    ]
    if not latest:
        out += ["No results to select from.", ""]
    elif selected is None:
        out += ["**No candidate meets the requirements yet.**", ""]
    else:
        out += [f"**Selected: `{selected.candidate.candidate_id}`** ({_params(selected)}).", ""]
    for cid in sorted(failures):
        if failures[cid]:
            out.append(f"* `{cid}` does not meet: " + "; ".join(failures[cid]))
    out += ["", "### Comparisons and regressions", ""]
    comps = comparisons(project, name)
    if not comps:
        out += [
            "No comparisons yet (they need a base model, release, or smaller model result).",
            "",
        ]
    for comp in comps:
        c, ref = comp.candidate.candidate.candidate_id, comp.reference.candidate.candidate_id
        changes = [f for f in comp.findings if f.kind.value != "unchanged"]
        out.append(
            f"* `{c}` vs. {comp.reference_kind} `{ref}`: "
            + (
                "; ".join(
                    f"**{f.kind.value}** {f.metric}: {f.message}"
                    + (" (CIs separated)" if f.significant else "")
                    for f in changes
                )
                or "no change beyond the thresholds."
            )
        )
    out.append("")
    return out


def _training_section(project: BenchmarkProject) -> list[str]:
    trainings = project.trainings()
    out = ["## Training runs", ""]
    if not trainings:
        return [*out, "No training runs recorded.", ""]
    out += [
        "| Run | Status | Label | Train / val examples | Steps | Last train loss | "
        "Last val loss | Dataset | Experiment |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for t in trainings:
        s = t.summary
        hp = s.hyperparameters
        train_losses = [p.train_loss for p in s.curve if p.train_loss is not None]
        val_losses = [p.val_loss for p in s.curve if p.val_loss is not None]
        out.append(
            f"| `{s.run_id}` | {t.status.value} | {hp.get('label', 'n/a')} | "
            f"{hp.get('train_examples', 'n/a')} / {hp.get('validation_examples', 'n/a')} | "
            f"{hp.get('global_steps', 'n/a')} | "
            f"{f'{train_losses[-1]:.3f}' if train_losses else 'n/a'} | "
            f"{f'{val_losses[-1]:.3f}' if val_losses else 'n/a'} | "
            f"`{s.dataset_fingerprint[:12]}` | `{t.experiment_id}` |"
        )
    return [*out, ""]


def build_report(project: BenchmarkProject) -> str:
    """Return the Markdown report (``docs/benchmarks.md``)."""
    records = project.benchmarks()
    out: list[str] = [HEADER, "", "# STEward benchmarks", ""]
    out += [
        "> **Not a certification.** These are automated, heuristic checks. A high score does not",
        "> mean the output is ASD-STE100 compliant. Automated, human-reviewed, and LLM-judged",
        "> metrics are kept separate; only automated metrics exist so far.",
        "",
        "How the benchmark system and its Claude Code hooks work: "
        "[benchmark-system.md](benchmark-system.md).",
        "",
    ]
    for name in project.suite_names():
        out += _suite_section(project, name, primary=name == project.primary_suite_name)
    out += _training_section(project)

    other = [
        r
        for r in records
        if r.status is RecordStatus.COMPLETED and r.comparability_key not in project.keys.values()
    ]
    failed = [r for r in records if r.status is RecordStatus.FAILED]
    pending = pending_candidates(project.registry, records, project.keys)
    warnings = evaluator_version_warnings(project, records)
    out += ["## Outstanding work", ""]
    items = []
    items += [f"Benchmark pending for registered candidate `{p}`." for p in pending]
    items += warnings
    items += [
        f"`{r.experiment_id}` (`{r.candidate.candidate_id}`) used `{r.comparability_key}`; it is "
        "kept in the history but is not directly comparable with current results."
        for r in other
    ]
    items += [
        f"Failed run `{r.experiment_id}` (`{r.candidate.candidate_id}`): {r.error}" for r in failed
    ]
    out += [f"* {i}" for i in items] or ["Nothing outstanding."]
    out.append("")

    out += ["## Figures", ""]
    for name in FIGURES:
        title = name.replace("_", " ").capitalize()
        out.append(f"### {title}\n\n![{title}](../benchmarks/figures/{name}.svg)\n")

    out += [
        "## Experiment history",
        "",
        "Full records: [`benchmarks/results/history.jsonl`](../benchmarks/results/history.jsonl).",
        "",
    ]
    history = project.history()
    if not history:
        out += ["The history is empty.", ""]
    else:
        out.append("| # | Experiment | Type | Date (UTC) | Candidate / run | Status | Commit |")
        out.append("|---|---|---|---|---|---|---|")
        for n, rec in enumerate(history, 1):
            name = (
                rec.candidate.candidate_id
                if isinstance(rec, BenchmarkRecord)
                else rec.summary.run_id
            )
            commit = (rec.code.git_commit or "")[:8] + ("+dirty" if rec.code.git_dirty else "")
            out.append(
                f"| {n} | `{rec.experiment_id}` | {rec.record_type} | "
                f"{rec.created_at:%Y-%m-%d %H:%M} | `{name}` | {rec.status.value} | "
                f"`{commit or 'n/a'}` |"
            )
        out.append("")
    out += [f"Training runs recorded: {len(project.trainings())}.", ""]

    out += ["## Metric definitions", "", "| Metric | Unit | Better | Group |", "|---|---|---|---|"]
    for name, info in METRICS.items():
        better = {True: "higher", False: "lower", None: "n/a"}[info.higher_is_better]
        out.append(f"| {info.label} (`{name}`) | {info.unit} | {better} | {info.group} |")
    out += [
        "",
        "Limitations: the rule checks are heuristic (see `src/steward/ste/rules.py`). Meaning "
        "preservation and hallucination use a fact proxy (numbers, required terms, safety labels, "
        "negation) and do not detect a changed meaning that keeps the same words. Language "
        "identification and negation detection for German, French, and Romanian use word lists "
        "(see `src/steward/ste/preservation.py`). chrF compares characters with a draft "
        "reference and is not a meaning judgment. All metrics are automated; no human-reviewed "
        "metric exists yet. Vocabulary compliance is not available because no licensed "
        "dictionary is configured.",
        "",
    ]
    return "\n".join(out)


def build_readme_section(project: BenchmarkProject) -> str:
    """The README block between the benchmark markers."""
    latest = latest_by_candidate(project.benchmarks(), project.key)
    req = _requirements(project, project.primary_suite_name)
    selected, _ = select_model(latest, req) if latest else (None, {})
    text_contract = project.suite.manifest.contract == "ste_only_text"
    lines = [README_START, "", "## Benchmarks", ""]
    if not latest:
        lines.append("No benchmark results yet.")
    else:
        lines.append(
            f"{len(latest)} candidates evaluated on `{project.suite.manifest.id}` "
            f"v{project.suite.manifest.version} ({project.suite.manifest.review_state} suite). "
            + (
                f"Smallest model that meets the requirements: `{selected.candidate.candidate_id}`."
                if selected
                else "No candidate meets the quality requirements yet."
            )
        )
    figures = (
        [
            ("STE-only output rate", "ste_only_output_rate"),
            ("Meaning preservation", "technical_meaning_preservation"),
            ("Quality versus model size", "quality_vs_size"),
            ("Training and validation loss", "training_loss"),
        ]
        if text_contract
        else [
            ("STE rule-check pass rate", "ste_compliance_by_model"),
            ("Pareto frontier", "pareto_frontier"),
        ]
    )
    lines.append("")
    for title, fig in figures:
        lines += [f"![{title}](benchmarks/figures/{fig}.svg)", ""]
    lines += [
        "Full report, regressions, and the experiment history: "
        "[docs/benchmarks.md](docs/benchmarks.md). Automated heuristic checks only; "
        "not ASD-STE100 certification.",
        "",
        README_END,
    ]
    return "\n".join(lines)


def update_readme(text: str, section: str) -> str:
    """Replace the marked section, or append it when the markers are missing."""
    pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.DOTALL)
    if pattern.search(text):
        return pattern.sub(lambda _: section, text)
    return text.rstrip("\n") + "\n\n" + section + "\n"


def render_text_outputs(project: BenchmarkProject) -> dict[Path, str]:
    """All generated text files and their content."""
    paths = project.paths
    readme = paths.readme.read_text(encoding="utf-8") if paths.readme.exists() else ""
    return {
        paths.report: build_report(project),
        paths.summary: json.dumps(build_summary(project), indent=2, sort_keys=True) + "\n",
        paths.readme: update_readme(readme, build_readme_section(project)),
    }
